// Regenerates themes/<slug>/card-fonts.generated.ts: the fonts a theme's share card needs,
// as base64 @font-face rules, so the card SVG is self-contained (an SVG drawn as an image
// cannot use the page's web fonts). Run after changing which fonts a card uses:
//   node scripts/embed-card-fonts.mjs
import { readFileSync, writeFileSync } from "node:fs";

const FONTS = {
  spacelog: [["Space Grotesk", "space-grotesk", 500]],
  notebook: [["Caveat", "caveat", 700], ["Lora", "lora", 400]],
  spellbook: [["Cinzel", "cinzel", 700], ["EB Garamond", "eb-garamond", 400]],
  dayzero: [["Bebas Neue", "bebas-neue", 400]],
};

for (const [slug, faces] of Object.entries(FONTS)) {
  const css = faces
    .map(([family, pkg, weight]) => {
      const b64 = readFileSync(`node_modules/@fontsource/${pkg}/files/${pkg}-latin-${weight}-normal.woff2`).toString("base64");
      return `@font-face{font-family:'${family}';font-weight:${weight};font-style:normal;src:url(data:font/woff2;base64,${b64}) format('woff2')}`;
    })
    .join("");
  writeFileSync(`themes/${slug}/card-fonts.generated.ts`, `// Generated by scripts/embed-card-fonts.mjs. Do not edit.\nexport const CARD_FONT_CSS = ${JSON.stringify(css)};\n`);
  console.log(slug, Math.round(css.length / 1024), "KB");
}
